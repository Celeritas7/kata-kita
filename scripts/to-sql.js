// Rows → idempotent SQL upserts. Safe to re-run against production: it never truncates,
// so user rows that reference content (user_words, review_log…) survive.
import { TABLE_ORDER } from '../supabase/seed/rows.js';

const CONFLICT = { word_parts: ['word_id', 'pos'], affix_roots: ['root'] };
const TEXT_ARRAY = { questions: ['alt_answers'] };
const SERIAL = ['unit_steps', 'words', 'proverbs', 'affix_forms', 'roleplay_turns', 'roleplay_replies', 'questions'];

const q = s => `'${String(s).replace(/'/g, "''")}'`;

function lit(v, table, col) {
  if (v == null) return 'null';
  if (TEXT_ARRAY[table]?.includes(col)) return v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return q(v);
}

export function toSql(rows) {
  let out = '-- Generated by scripts/build-seed.mjs from supabase/seed/content.js. Do not edit by hand.\n\nbegin;\n';
  for (const table of TABLE_ORDER) {
    const list = rows[table];
    if (!list?.length) continue;
    const cols = Object.keys(list[0]);
    const key = CONFLICT[table] || ['id'];
    const upd = cols.filter(c => !key.includes(c));
    out += `\n-- ${table} (${list.length})\ninsert into ${table} (${cols.join(', ')}) values\n`;
    out += list.map(r => `  (${cols.map(c => lit(r[c], table, c)).join(', ')})`).join(',\n');
    out += `\non conflict (${key.join(', ')}) do ${upd.length ? 'update set ' + upd.map(c => `${c} = excluded.${c}`).join(', ') : 'nothing'};\n`;
  }
  out += '\n-- keep serial sequences ahead of the explicit ids\n';
  out += SERIAL.map(t => `select setval(pg_get_serial_sequence('${t}', 'id'), (select coalesce(max(id), 1) from ${t}));`).join('\n');
  out += '\n\ncommit;\n';
  return out;
}
